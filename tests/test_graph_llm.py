"""Fase 1.3 — Test del Port LanguageModel e del FakeLLM (no MLX).

Verifica il contratto, le tre modalita' del Fake (risposta fissa / handler / errore)
e la registrazione delle chiamate per gli assert del grafo.
"""

from __future__ import annotations

import pytest

from src.graph.llm import FakeLLM, LanguageModel, MLXModel, FallbackLLM
from src.serving.multiplexer import ModelMultiplexer, FakeModelRuntime
from tests.conftest import needs_mlx

class TestContratto:
    def test_fake_e_un_language_model(self):
        assert isinstance(FakeLLM(), LanguageModel)


class TestModalita:
    def test_risposta_fissa(self):
        llm = FakeLLM("il prezzo e' 12,50")
        assert llm.generate("sys", "quanto costa?") == "il prezzo e' 12,50"

    def test_default_stringa_vuota(self):
        assert FakeLLM().generate("s", "u") == ""

    def test_handler_dipende_dall_input(self):
        llm = FakeLLM(handler=lambda system, user: f"eco:{user}")
        assert llm.generate("sys", "ciao") == "eco:ciao"

    def test_handler_ha_precedenza_su_response(self):
        llm = FakeLLM("fissa", handler=lambda s, u: "dinamica")
        assert llm.generate("s", "u") == "dinamica"

    def test_errore_sollevato(self):
        # fail-closed: il grafo deve poter osservare l'eccezione, non un valore muto
        llm = FakeLLM(error=RuntimeError("modello non disponibile"))
        with pytest.raises(RuntimeError, match="non disponibile"):
            llm.generate("s", "u")


class TestRegistrazione:
    def test_registra_le_chiamate(self):
        llm = FakeLLM("ok")
        llm.generate("sys1", "u1")
        llm.generate("sys2", "u2")
        assert llm.calls == [("sys1", "u1"), ("sys2", "u2")]

class TestMLXModel:
    def test_mlx_model_invariants(self):
        # Invarianti: use-prima-di-generate, clamp ctx, opzioni passate al runtime
        runtime = FakeModelRuntime()
        multiplexer = ModelMultiplexer(runtime, max_resident=1, ctx_cap=8000)
        
        # Facciamo scattare il dummy generate patchando il FakeModelRuntime
        def dummy_generate(name, messages, **kwargs):
            return f"generated by {name} with temp {kwargs.get('temp')}"
        runtime.generate = dummy_generate
        
        llm = MLXModel("test-model", multiplexer, options={"temp": 0.5})
        
        out = llm.generate("sys", "user")
        assert out == "generated by test-model with temp 0.5"
        
        # Verifica eviction e load (use() chiamato)
        assert "test-model" in runtime.resident()
        # FakeModelRuntime registra (load, name, num_ctx)
        assert ("load", "test-model", 8000) in runtime.calls


class TestFallbackLLM:
    def test_fallback_success(self, caplog):
        primary = FakeLLM(error=RuntimeError("primary failed"))
        fallback = FakeLLM(response="fallback success")
        
        llm = FallbackLLM(primary, fallback)
        out = llm.generate("sys", "user")
        
        assert out == "fallback success"
        assert "primary failed" in caplog.text
        assert "Subentra fallback" in caplog.text


@pytest.mark.needs_mlx
@needs_mlx
def test_mlx_model_real():
    """Test di integrazione: carica il modello reale e genera 1 token.
    Se RUN_MLX=1, carica il modello ed esplode se non c'e' mlx-lm o RAM."""
    from src.serving.multiplexer import MlxModelRuntime
    from src.backend.config import settings
    
    runtime = MlxModelRuntime()
    multiplexer = ModelMultiplexer(runtime)
    llm = MLXModel(settings.logic_model, multiplexer, options={"max_tokens": 5})
    
    # Questo fara' il load vero e proprio e generera' 1 token.
    # Se il modello non esiste o la RAM non basta, DEVE fallire rumorosamente.
    out = llm.generate("Sei un assistente.", "Ciao")
    assert isinstance(out, str)
    assert len(out) > 0
    print(f"Generato: {out!r}")
